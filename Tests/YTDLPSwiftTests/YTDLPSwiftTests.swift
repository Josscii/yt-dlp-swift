import Testing
@testable import YTDLPSwift

@Test func testValidYouTubeURLs() async throws {
    let extractor = YouTubeExtractor()
    
    // Test valid YouTube URLs
    #expect(extractor.isValidYouTubeURL("https://www.youtube.com/watch?v=dQw4w9WgXcQ"))
    #expect(extractor.isValidYouTubeURL("https://youtube.com/watch?v=dQw4w9WgXcQ"))
    #expect(extractor.isValidYouTubeURL("https://m.youtube.com/watch?v=dQw4w9WgXcQ"))
    #expect(extractor.isValidYouTubeURL("https://youtu.be/dQw4w9WgXcQ"))
    #expect(extractor.isValidYouTubeURL("https://www.youtu.be/dQw4w9WgXcQ"))
    
    // Test invalid URLs
    #expect(!extractor.isValidYouTubeURL("https://example.com/watch?v=dQw4w9WgXcQ"))
    #expect(!extractor.isValidYouTubeURL("https://www.youtube.com/watch"))
    #expect(!extractor.isValidYouTubeURL("not-a-url"))
    #expect(!extractor.isValidYouTubeURL(""))
}

@Test func testVideoIdExtraction() async throws {
    let extractor = YouTubeExtractor()
    
    // Test video ID extraction from different URL formats
    #expect(extractor.extractVideoId(from: "https://www.youtube.com/watch?v=dQw4w9WgXcQ") == "dQw4w9WgXcQ")
    #expect(extractor.extractVideoId(from: "https://youtu.be/dQw4w9WgXcQ") == "dQw4w9WgXcQ")
    #expect(extractor.extractVideoId(from: "https://youtube.com/watch?v=dQw4w9WgXcQ&feature=youtu.be") == "dQw4w9WgXcQ")
    
    // Test invalid URLs
    #expect(extractor.extractVideoId(from: "https://example.com/watch?v=dQw4w9WgXcQ") == nil)
    #expect(extractor.extractVideoId(from: "https://www.youtube.com/watch") == nil)
    #expect(extractor.extractVideoId(from: "not-a-url") == nil)
}

@Test func testVideoFormatInitialization() async throws {
    let format = VideoFormat(
        formatId: "22",
        url: "https://example.com/video.mp4",
        resolution: "1280x720",
        width: 1280,
        height: 720,
        fps: 30,
        videoBitrate: 2500,
        audioBitrate: 192,
        container: "mp4",
        videoCodec: "avc1.4d401f",
        audioCodec: "mp4a.40.2"
    )
    
    #expect(format.formatId == "22")
    #expect(format.resolution == "1280x720")
    #expect(format.width == 1280)
    #expect(format.height == 720)
    #expect(format.fps == 30)
    #expect(format.videoBitrate == 2500)
    #expect(format.audioBitrate == 192)
    #expect(!format.isVideoOnly)
    #expect(!format.isAudioOnly)
}

