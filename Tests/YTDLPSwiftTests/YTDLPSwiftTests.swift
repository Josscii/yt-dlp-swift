@Test func testVideoInfoInitialization() async throws {
    let formats = [
        VideoFormat(formatId: "140", url: "https://example.com/audio.m4a", isAudioOnly: true),
        VideoFormat(formatId: "22", url: "https://example.com/video.mp4", resolution: "1280x720")
    ]
    
    let subtitles = [
        Subtitle(language: "en", languageName: "English", url: "https://example.com/en.vtt", format: "vtt")
    ]
    
    let videoInfo = VideoInfo(
        id: "dQw4w9WgXcQ",
        title: "Test Video",
        description: "A test video",
        uploader: "Test Channel",
        duration: 213,
        viewCount: 1000000,
        thumbnail: "https://img.youtube.com/vi/dQw4w9WgXcQ/maxresdefault.jpg",
        formats: formats,
        subtitles: subtitles
    )
    
    #expect(videoInfo.id == "dQw4w9WgXcQ")
    #expect(videoInfo.title == "Test Video")
    #expect(videoInfo.description == "A test video")
    #expect(videoInfo.uploader == "Test Channel")
    #expect(videoInfo.duration == 213)
    #expect(videoInfo.viewCount == 1000000)
    #expect(videoInfo.formats.count == 2)
    #expect(videoInfo.subtitles.count == 1)
}

@Test func testYouTubeExtractorErrors() async throws {
    let extractor = YouTubeExtractor()
    
    // Test invalid URL error
    do {
        _ = try await extractor.extractVideoInfo(from: "https://example.com/invalid")
        #expect(Bool(false), "Should have thrown an error")
    } catch YouTubeExtractorError.invalidURL {
        // Expected error
        #expect(Bool(true))
    } catch {
        #expect(Bool(false), "Wrong error type thrown: \(error)")
    }
    
    // Test video ID not found error (valid YouTube domain but no video ID)
    do {
        _ = try await extractor.extractVideoInfo(from: "https://youtube.com/playlist")
        #expect(Bool(false), "Should have thrown an error")
    } catch YouTubeExtractorError.videoIdNotFound {
        // Expected error  
        #expect(Bool(true))
    } catch YouTubeExtractorError.invalidURL {
        // This is also acceptable since no video ID means invalid for our purposes
        #expect(Bool(true))
    } catch {
        #expect(Bool(false), "Wrong error type thrown: \(error)")
    }
}
